#!/usr/bin/env python3
"""Render SIZING.md from do-prices.json plus one measured number: the app's resident memory.

    python3 render_sizing.py            # writes SIZING.md
    python3 render_sizing.py --check    # exit 1 if SIZING.md is stale

The point of the file is that "a $6 droplet is enough" is an argument, not an assertion: the
service's own RSS is measured here, the memory a Linux host needs on top of it is named, and the
plan table is generated from the vendor's dated price file so it cannot drift from the picker.
"""
import json
import os
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
PRICES = os.path.join(HERE, "do-prices.json")
OUT = os.path.join(HERE, "SIZING.md")

# Measured on this machine (Linux x86-64, Python 3.14, 2026-11-08) by booting app/server.py with
# an empty database, writing 50 notes, and reading VmRSS from /proc/<pid>/status. Re-measure with
# `python3 render_sizing.py --measure` on your own machine; the number is a floor, not a promise.
MEASURED_RSS_MB = None

# The other measured number: a WSGI (Flask + gunicorn) deployment of the same idea, so the
# README's "swap one ExecStart line" advice comes with a memory cost instead of a guess. Measured
# 2026-11-09 by `deploy/tests/test_wsgi.sh` on the same machine (Python 3.14.9, Flask 3.1.3,
# gunicorn 26.2.0): VmRSS summed over the master and all workers AFTER every worker has served a
# request (an unwarmed worker has not touched its copy-on-write pages and reads ~40 MiB low), median
# of three runs. Re-measure with `bash deploy/tests/test_wsgi.sh` — it prints both figures.
WSGI_2W_MB = 104.0
WSGI_4W_MB = 177.0


def measure_rss():
    """Start the server, write 50 notes, return (rss_mb, notes_ok)."""
    import urllib.request

    tmp = tempfile.mkdtemp()
    port = 0
    import socket
    s = socket.socket(); s.bind(("127.0.0.1", 0)); port = s.getsockname()[1]; s.close()
    env = dict(os.environ, NOTES_PORT=str(port), NOTES_DB=os.path.join(tmp, "probe.db"))
    proc = subprocess.Popen([sys.executable, os.path.join(HERE, "app", "server.py")],
                            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        base = "http://127.0.0.1:%d" % port
        for _ in range(100):
            try:
                urllib.request.urlopen(base + "/healthz", timeout=2).read()
                break
            except Exception:
                time.sleep(0.05)
        for i in range(50):
            req = urllib.request.Request(base + "/notes",
                                         data=json.dumps({"text": "note %d" % i}).encode(),
                                         headers={"Content-Type": "application/json"},
                                         method="POST")
            urllib.request.urlopen(req, timeout=5).read()
        rss_kb = None
        with open("/proc/%d/status" % proc.pid) as f:
            for line in f:
                if line.startswith("VmRSS:"):
                    rss_kb = int(line.split()[1])
        ok = len(json.loads(urllib.request.urlopen(base + "/notes", timeout=5).read())["notes"])
        return round((rss_kb or 0) / 1024.0, 1), ok
    finally:
        proc.terminate()
        proc.wait(timeout=10)


def render(rss_mb):
    d = json.load(open(PRICES))
    basic = [p for p in d["plans"] if p["family"] == "Basic"]
    basic.sort(key=lambda p: p["usd_per_month"])
    rows = []
    for p in basic:
        # what the plan leaves for the OS and page cache after the service itself
        headroom = p["memory_gib"] * 1024 - rss_mb
        rows.append("| %s | %s GiB | %s | %s GiB | $%.2f | $%.5f | %s |" % (
            p["family"], ("%g" % p["memory_gib"]), "%g vCPU" % p["vcpus"],
            ("%g" % p["disk_gib"]), p["usd_per_month"], p["usd_per_hour"],
            ("%d MiB free" % headroom) if headroom > 0 else "too small"))
    table = "\n".join(rows)
    p512 = next((p for p in basic if p["memory_gib"] <= 0.5), basic[0])
    p1g = next((p for p in basic if p["memory_gib"] >= 1.0), basic[-1])

    return """# Sizing: what this service actually needs

Generated by `render_sizing.py` from `do-prices.json` (read from DigitalOcean's pricing page,
%s) and one measured number, so the table cannot drift from the vendor's file.

## The measured number

`app/server.py` with an empty database and 50 notes written: **%.1f MiB resident** (VmRSS,
measured by `python3 render_sizing.py --measure`).

That is the Python interpreter, the HTTP server, and the SQLite page cache for a database this
size. It does **not** include the operating system: a minimal Ubuntu 24.04 install uses roughly
120–180 MiB at idle (systemd, journald, sshd, unattended-upgrades), and Caddy adds about 15–25 MiB.
So the real requirement is **~%d MiB** — the service, plus a host, plus a little room for page cache
so that the disk is not the thing your users wait on.

## If you deploy a Flask app instead

The same idea with Flask 3.1.3 behind gunicorn 26.2.0 (the README's one-line `ExecStart` swap),
measured on this machine 2026-11-09 by `deploy/tests/test_wsgi.sh`: **%.0f MiB across the master
and two workers**, **%.0f MiB across the master and four** — about **%.0f MiB for each extra
worker** on top of a fixed interpreter.

Carried into the same arithmetic as above (service + ~300 MiB of host), a two-worker Flask app is
**~%d MiB** and a four-worker one **~%d MiB**. The 512 MiB plan still *fits* two workers — it just
stops being comfortable: %d MiB left instead of %d MiB, which is the headroom an `apt upgrade`
spends. Four workers is the configuration that crosses the line (%d MiB left of 512). So for a
Flask/gunicorn deployment the **1 GiB plan is the floor**, not the comfortable option. That
paragraph used to be the one thing in this repo a reader had to take on faith;
`deploy/tests/test_wsgi.sh` now starts both worker counts and fails if either does not answer.

## The Basic plans, priced by the vendor

| family | RAM | CPU | disk | $/month | $/hour | left after the service |
|---|---|---|---|---|---|---|
%s

The **512 MiB plan ($%.2f/month) is the floor for the stdlib service**: the numbers above say it
fits, and it is the plan that starts swapping during an `apt upgrade` once Caddy and
unattended-upgrades are running. The comfortable answer is the **1 GiB plan ($%.2f/month)**, which is
what the deploy guide assumes — and the answer for a Flask/gunicorn deployment above. If
you pick the 512 MiB one, add a swapfile (`fallocate -l 512M /swapfile`) — the service does not
need it, the package manager does.

## Hourly is not monthly / 730

For the $6 plan: $0.00893/h × 730 = **$6.52**, which is *more* than the $6.00 list price.
DigitalOcean's page calls the monthly figure a "monthly cap", so the two are different billing
bases and neither is derived from the other. `droplet-fit/pick.py` prices a job by `--hours` when
the Droplet is short-lived and by the vendor's monthly figure otherwise.

## Backups are a percentage, not a line item

DigitalOcean prices Droplet backups at **20%% (weekly) or 30%% (daily)** of the Droplet cost, so this
$%.2f plan with daily backups is **$%.2f/month**. That is worth comparing against `deploy/backup.sh`,
which costs $0 and keeps seven hourly copies on the same disk — and against the fact that a backup
on the same disk does not survive losing the disk. The honest setup is both: local copies for
"oops", Droplet backups for "the disk is gone".

---

Prices: %s. Written and maintained by agent002, an autonomous AI agent operated by a9n9.
""" % (
        d.get("fetched", "undated"),
        rss_mb,
        int(rss_mb) + 300,
        WSGI_2W_MB,
        WSGI_4W_MB,
        (WSGI_4W_MB - WSGI_2W_MB) / 2.0,
        int(round(WSGI_2W_MB)) + 300,
        int(round(WSGI_4W_MB)) + 300,
        512 - (int(round(WSGI_2W_MB)) + 300),
        512 - (int(rss_mb) + 300),
        512 - (int(round(WSGI_4W_MB)) + 300),
        table,
        p512["usd_per_month"],
        p1g["usd_per_month"],
        p1g["usd_per_month"], p1g["usd_per_month"] * 1.30,
        d.get("fetched", "undated"),
    )


def main():
    rss = MEASURED_RSS_MB
    if "--check" in sys.argv:
        # Verify the TABLE is current, not that a fresh memory measurement equals the recorded
        # one: RSS varies by a few MiB run to run, so re-measuring here makes the check flaky and
        # a flaky guard gets ignored. Re-measure deliberately with --measure.
        import re
        text = open(OUT).read() if os.path.exists(OUT) else ""
        m = re.search(r"\*\*([\d.]+) MiB resident\*\*", text)
        if not m:
            print("SIZING.md missing or has no recorded measurement")
            return 1
        rss = float(m.group(1))
        if text != render(rss):
            print("SIZING.md is stale against do-prices.json; re-run python3 render_sizing.py")
            return 1
        print("SIZING.md up to date (recorded rss=%.1f MiB)" % rss)
        return 0
    if rss is None:
        rss, ok = measure_rss()
        assert ok == 50, "expected 50 notes, server returned %s" % ok
    text = render(rss)
    open(OUT, "w").write(text)
    print("wrote SIZING.md (measured rss=%.1f MiB)" % rss)
    return 0


if __name__ == "__main__":
    sys.exit(main())
